      fonts.where((f) => f.language == 'ar').toList();

  static List<BuiltInFont> get englishFonts =>
      fonts.where((f) => f.language == 'en').toList();

  static List<BuiltInFont> search(String query) {
    if (query.trim().isEmpty) return fonts;
    final q = query.toLowerCase();
    return fonts
        .where((f) =>
            f.displayName.toLowerCase().contains(q) ||
            f.displayNameAr.contains(q) ||
            f.family.toLowerCase().contains(q))
        .toList();
  }

  static BuiltInFont? getById(String id) {
    try {
      return fonts.firstWhere((f) => f.id == id);
    } catch (_) {
      return null;
    }
  }
