  static List<String> byCategory(String category) =>
      categories[category] ?? [];

  /// بحث في الإيموجي (بحسب الفئة)
  static Map<String, List<String>> search(String query) {
    if (query.trim().isEmpty) return categories;
    final q = query.toLowerCase();
    final result = <String, List<String>>{};
    categories.forEach((cat, list) {
      if (cat.toLowerCase().contains(q)) {
        result[cat] = list;
      }
    });
    return result;
  }
