/// فئة إيموجي
class EmojiCategory {
  final String name;
  final List<String> emojis;

  const EmojiCategory({required this.name, required this.emojis});

  int get count => emojis.length;
}

/// الكل كـ قائمة فئات
class EmojiAll {
  EmojiAll._();

  static List<EmojiCategory> get categoriesList {
    return EmojisCatalog.categories.entries
        .map((e) => EmojiCategory(name: e.key, emojis: e.value))
        .toList();
  }

  static int get total => EmojisCatalog.total;
}
