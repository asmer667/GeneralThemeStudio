/// خدمة تصدير الثيم الكاملة
class ThemeExportService {
  ThemeExportService._();

  // ═══════════════════════════════════════════
  // TOML Generation
  // ═══════════════════════════════════════════

  static String generateThemeToml(ThemeProject p) {
    final sb = StringBuffer();

    // Header
    sb.writeln('# Generated by ${AppConstants.appName}');
    sb.writeln('# Version: ${AppConstants.appVersion}');
    sb.writeln('# Build: ${DateTime.now().toIso8601String()}');
    sb.writeln('# Validate with FUTO Keyboard before publishing.');
    sb.writeln();

    // Metadata
    sb.writeln('name = "${_escape(p.name)}"');
    sb.writeln('author = "${_escape(p.author)}"');
    sb.writeln('id = "${p.id}"');
    sb.writeln('version = ${p.version}');
    sb.writeln('description = "${_escape(p.description)}"');
    sb.writeln();

    // Options
    sb.writeln('[options]');
    sb.writeln('auto_borders = ${p.autoBorders}');
    sb.writeln('center_hints = ${p.centerHints}');
    sb.writeln('roundedness = ${p.roundedness.toStringAsFixed(2)}');
    sb.writeln('scale_text = ${p.scaleText.toStringAsFixed(2)}');
    sb.writeln('scale_hints = ${p.scaleHints.toStringAsFixed(2)}');
    sb.writeln('weight_text = ${p.weightText}');
    sb.writeln('weight_hints = ${p.weightHints}');
    sb.writeln();

    // Colors
    _writeColors(sb, p);

    // Keyboard colors
    _writeKeyboardColors(sb, p);

    // Background image (FUTO format)
    _writeBackground(sb, p);

    // Match rules (from groups)
    _writeMatchRules(sb, p);

    // Assets (borders + icons)
    _writeAssets(sb, p);

    return sb.toString();
  }

  // ═══════════════════════════════════════════
  // Colors
  // ═══════════════════════════════════════════

  static void _writeColors(StringBuffer sb, ThemeProject p) {
    sb.writeln('[colors]');
    sb.writeln('primary = "${ColorUtils.toHex(p.primary)}"');
    sb.writeln('on_primary = "${ColorUtils.toHex(p.onPrimary)}"');
    sb.writeln(
        'primary_container = "${ColorUtils.toHex(p.primaryContainer)}"');
    sb.writeln(
        'on_primary_container = "${ColorUtils.toHex(p.onPrimaryContainer)}"');
    sb.writeln('inverse_primary = "${ColorUtils.toHex(p.secondary)}"');
    sb.writeln('secondary = "${ColorUtils.toHex(p.secondary)}"');
    sb.writeln('on_secondary = "${ColorUtils.toHex(p.onSecondary)}"');
    sb.writeln(
        'secondary_container = "${ColorUtils.toHex(p.secondaryContainer)}"');
    sb.writeln(
        'on_secondary_container = "${ColorUtils.toHex(p.onSecondaryContainer)}"');
    sb.writeln('tertiary = "${ColorUtils.toHex(p.tertiary)}"');
    sb.writeln('on_tertiary = "${ColorUtils.toHex(p.onTertiary)}"');
    sb.writeln(
        'tertiary_container = "${ColorUtils.toHex(p.secondaryContainer)}"');
    sb.writeln(
        'on_tertiary_container = "${ColorUtils.toHex(p.onSecondaryContainer)}"');
    sb.writeln('background = "${ColorUtils.toHex(p.background)}"');
    sb.writeln('on_background = "${ColorUtils.toHex(p.onBackground)}"');

    // Surface family
    sb.writeln('surface = "${ColorUtils.toHex(p.surface)}"');
    sb.writeln(
        'surface_dim = "${ColorUtils.toHex(ColorUtils.adjustBrightness(p.surface, -0.05))}"');
    sb.writeln(
        'surface_bright = "${ColorUtils.toHex(ColorUtils.adjustBrightness(p.surface, 0.08))}"');
    sb.writeln(
        'surface_container_lowest = "${ColorUtils.toHex(ColorUtils.adjustBrightness(p.surface, 0.03))}"');
    sb.writeln(
        'surface_container_low = "${ColorUtils.toHex(ColorUtils.adjustBrightness(p.surface, 0.06))}"');
    sb.writeln(
        'surface_container = "${ColorUtils.toHex(p.keyboardContainer)}"');
    sb.writeln(
        'surface_container_high = "${ColorUtils.toHex(ColorUtils.adjustBrightness(p.keyboardContainer, 0.05))}"');
    sb.writeln(
        'surface_container_highest = "${ColorUtils.toHex(ColorUtils.adjustBrightness(p.keyboardContainer, 0.10))}"');
    sb.writeln('on_surface = "${ColorUtils.toHex(p.onSurface)}"');
    sb.writeln('surface_variant = "${ColorUtils.toHex(p.surfaceVariant)}"');
    sb.writeln(
        'on_surface_variant = "${ColorUtils.toHex(p.onSurfaceVariant)}"');
    sb.writeln('surface_tint = "${ColorUtils.toHex(p.primary)}"');
    sb.writeln('inverse_surface = "${ColorUtils.toHex(p.onSurface)}"');
    sb.writeln('inverse_on_surface = "${ColorUtils.toHex(p.surface)}"');

    // Error
    sb.writeln('error = "${ColorUtils.toHex(p.error)}"');
    sb.writeln('on_error = "${ColorUtils.toHex(p.onError)}"');
    sb.writeln('error_container = "#FFDAD4FF"');
    sb.writeln('on_error_container = "#2A1613FF"');

    // Outline
    sb.writeln('outline = "${ColorUtils.toHex(p.outline)}"');
    sb.writeln('outline_variant = "${ColorUtils.toHex(p.outlineVariant)}"');
    sb.writeln('scrim = "#000000FF"');
    sb.writeln();
  }

  static void _writeKeyboardColors(StringBuffer sb, ThemeProject p) {
    sb.writeln('keyboard_surface = "${ColorUtils.toHex(p.keyboardSurface)}"');
    sb.writeln(
        'keyboard_surface_dim = "${ColorUtils.toHex(ColorUtils.adjustBrightness(p.keyboardSurface, -0.05))}"');
    sb.writeln(
        'keyboard_container = "${ColorUtils.toHex(p.keyboardContainer)}"');
    sb.writeln(
        'keyboard_container_variant = "${ColorUtils.toHex(p.keyboardContainerVariant)}"');
    sb.writeln(
        'on_keyboard_container = "${ColorUtils.toHex(p.onKeyboardContainer)}"');
    sb.writeln('keyboard_press = "${ColorUtils.toHex(p.keyboardPress)}"');
    sb.writeln(
        'keyboard_container_pressed = "${ColorUtils.toHex(p.keyboardContainerPressed)}"');
    sb.writeln(
        'on_keyboard_container_pressed = "${ColorUtils.toHex(p.onKeyboardContainerPressed)}"');
    sb.writeln();
  }

  static void _writeBackground(StringBuffer sb, ThemeProject p) {
    final bg = p.background;
    if (bg == null) return;

    sb.writeln('# ═══ Background ═══');
    sb.writeln('background_type = "${bg.type.name}"');

    switch (bg.type) {
      case BackgroundType.color:
        if (bg.solidColor != null) {
          sb.writeln(
              'background_color = "${ColorUtils.toHex(bg.solidColor!)}"');
        }
        break;
      case BackgroundType.gradient:
        if (bg.gradientColors != null && bg.gradientColors!.isNotEmpty) {
          sb.writeln(
              'background_gradient_colors = [${bg.gradientColors!.map((c) => '"${ColorUtils.toHex(c)}"').join(", ")}]');
          sb.writeln('background_gradient_angle = ${bg.gradientAngle}');
        }
        break;
      case BackgroundType.image:
      case BackgroundType.builtin:
        if (bg.imagePath != null) {
          final fileName = bg.imagePath!.split('/').last;
          sb.writeln('background_image = "$fileName"');
          sb.writeln('background_image_opacity = ${bg.opacity}');
          if (bg.blurAmount > 0) {
            sb.writeln('background_image_blur = ${bg.blurAmount}');
          }
        }
        break;
      case BackgroundType.mesh:
        if (bg.gradientColors != null) {
          sb.writeln(
              'background_mesh_colors = [${bg.gradientColors!.map((c) => '"${ColorUtils.toHex(c)}"').join(", ")}]');
        }
        break;
    }
    sb.writeln();
  }

  static void _writeMatchRules(StringBuffer sb, ThemeProject p) {
    final allRules = <String>[];
    for (final group in p.groups) {
      for (final rule in group.toMatchRules()) {
        allRules.add(rule.toTomlSection());
      }
    }
    if (allRules.isNotEmpty) {
      sb.writeln('# ═══ Match Rules ═══');
      sb.writeln(allRules.join('\n'));
    }
  }

  static void _writeAssets(StringBuffer sb, ThemeProject p) {
    // Borders
    final borderSections = <String>[];
    final seenBorders = <String>{};
    for (final group in p.groups) {
      for (final b in [
        group.border,
        group.pressedBorder,
        group.longPressBorder
      ]) {
        if (b != null && seenBorders.add(b.name)) {
          borderSections.add(b.toTomlSection());
        }
      }
    }
    if (borderSections.isNotEmpty) {
      sb.writeln();
      sb.writeln('# ═══ Border Assets ═══');
      sb.writeln(borderSections.join('\n'));
    }

    // Icons
    final iconSections = <String>[];
    final seenIcons = <String>{};
    for (final group in p.groups) {
      for (final i in [group.icon, group.pressedIcon]) {
        if (i != null && seenIcons.add(i.name)) {
          iconSections.add(i.toTomlSection());
        }
      }
    }
    if (iconSections.isNotEmpty) {
      sb.writeln();
      sb.writeln('# ═══ Icon Assets ═══');
      sb.writeln(iconSections.join('\n'));
    }
  }

  // ═══════════════════════════════════════════
  // Collect Assets
  // ═══════════════════════════════════════════

  static ({List<BorderAsset> borders, List<IconAsset> icons}) collectAssets(
      ThemeProject p) {
    final borders = <BorderAsset>[];
    final icons = <IconAsset>[];
    final seenBorders = <String>{};
    final seenIcons = <String>{};

    for (final g in p.groups) {
      for (final b in [g.border, g.pressedBorder, g.longPressBorder]) {
        if (b != null && seenBorders.add(b.name)) borders.add(b);
      }
      for (final i in [g.icon, g.pressedIcon]) {
        if (i != null && seenIcons.add(i.name)) icons.add(i);
      }
    }

    return (borders: borders, icons: icons);
  }

  // ═══════════════════════════════════════════
  // Export
  // ═══════════════════════════════════════════

  static Future<ExportResult> exportTheme(
    ThemeProject project, {
    String? outputName,
  }) async {
    final assets = collectAssets(project);
    final assetsDir = await AssetGeneratorService.createAssetsDir();

    // 1. توليد صور الأزرار والأيقونات
    await AssetGeneratorService.generateAllAssets(
      borders: assets.borders,
      icons: assets.icons,
      outputDir: assetsDir,
    );

    // 2. theme.txt
    final themeToml = generateThemeToml(project);
    final themeBytes = Uint8List.fromList(themeToml.codeUnits);

    // 3. README
    final readme = _generateReadme(project);
    final readmeBytes = Uint8List.fromList(readme.codeUnits);

    // 4. LICENSE
    final license = _generateLicense();
    final licenseBytes = Uint8List.fromList(license.codeUnits);

    // 5. جميع الملفات
    final files = <String, Uint8List>{
      AppConstants.themeConfigFile: themeBytes,
      AppConstants.themeReadmeFile: readmeBytes,
      AppConstants.themeLicenseFile: licenseBytes,
    };

    // إضافة الأصول المولّدة
    final generated = assetsDir.listSync();
    for (final f in generated) {
      if (f is File) {
        final name = f.uri.pathSegments.last;
        files[name] = await f.readAsBytes();
      }
    }

    // إضافة الخلفية إن وُجدت
    final bg = project.background;
    if (bg != null &&
        (bg.type == BackgroundType.image ||
            bg.type == BackgroundType.builtin) &&
        bg.imagePath != null) {
      try {
        final bgFile = File(bg.imagePath!);
        if (await bgFile.exists()) {
          files['background.png'] = await bgFile.readAsBytes();
        }
      } catch (_) {}
    }

    // إضافة الخط إن وُجد
    if (project.fontPath != null) {
      try {
        final fontFile = File(project.fontPath!);
        if (await fontFile.exists()) {
          files['font.ttf'] = await fontFile.readAsBytes();
        }
      } catch (_) {}
    }

    // 6. ZIP
    final zipName = outputName ??
        '${project.name.replaceAll(" ", "_")}_${DateTime.now().millisecondsSinceEpoch}.zip';
    final zipFile = await ZipService.createZip(
      files: files,
      outputName: zipName,
    );

    return ExportResult(
      file: zipFile,
      fileCount: files.length,
      totalSize: await zipFile.length(),
      project: project,
    );
  }

  // ═══════════════════════════════════════════
  // Helpers
  // ═══════════════════════════════════════════

  static String _escape(String s) => s.replaceAll('"', '\\"');

  static String _generateReadme(ThemeProject p) {
    final bg = p.background;
    return '''# ${p.name}

**Author:** ${p.author}
**Theme ID:** ${p.id}
**Version:** ${p.version}

## Description

${p.description}

## Theme Details

- **Groups:** ${p.groups.length}
- **Total Assets:** ${p.groups.fold<int>(0, (sum, g) => sum + g.assetCount)}
- **Roundedness:** ${(p.roundedness * 100).toStringAsFixed(0)}%
- **Background:** ${bg?.name ?? "none"}
- **Font:** ${p.fontName ?? "default"}
- **Created:** ${p.createdAt.toString().split('.')[0]}
- **Updated:** ${p.updatedAt.toString().split('.')[0]}

## How to Import

1. Open FUTO Keyboard
2. Go to Settings → Themes → Import
3. Select this ZIP file
4. Apply the theme

## Created With

${AppConstants.appName} v${AppConstants.appVersion}
''';
  }

